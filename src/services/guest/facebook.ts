/**
 * PHILRADS's Facebook posts for guest Disaster News, through an rss.app feed of the page
 * (facebook.com/philradsorg). rss.app gives the same feed as JSON (feeds/v1.1/<id>.json) or as
 * RSS (feeds/<id>.xml); both are read here.
 *
 * The feed's address is a server setting (FACEBOOK_FEED_URL in Vercel), read by
 * /api/weather?facebook=page, which caches the posts at Vercel's edge for everyone. No
 * browser-only code here: the server function imports it too.
 */

export interface FacebookPost {
  id: string;
  /** The post on Facebook. */
  url: string;
  text: string;
  /** The post's first picture, if it has one. */
  image: string | null;
  postedAt: string | null;
}

export interface FacebookFeed {
  posts: FacebookPost[];
  /** The page itself, for "See all on Facebook". */
  page: string;
  checkedAt: string;
}

export const FACEBOOK_PAGE = 'https://www.facebook.com/philradsorg';
/** How many posts are kept: guests see a few, then "Show more". */
const KEEP = 12;

/** Only rss.app feeds, over https: the setting can't turn the function into an open proxy. */
export function validFeedUrl(raw: string | undefined): string | null {
  if (!raw) return null;
  try {
    const u = new URL(raw.trim());
    return u.protocol === 'https:' && (u.hostname === 'rss.app' || u.hostname.endsWith('.rss.app')) ? u.toString() : null;
  } catch {
    return null;
  }
}

const ENTITIES: Record<string, string> = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
const decode = (s: string) =>
  s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e: string) => {
    if (e[0] === '#') {
      const n = e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(n) && n > 0 && n < 0x110000 ? String.fromCodePoint(n) : m;
    }
    return ENTITIES[e.toLowerCase()] ?? m;
  });

/** Plain text from a post's HTML: line breaks kept, tags and the "(Feed generated with …)" footer dropped. */
export function plainText(html: string) {
  const text = decode(
    html
      .replace(/<!\[CDATA\[|\]\]>/g, '')
      .replace(/<br\s*\/?>/gi, '\n')
      .replace(/<\/(p|div|li)>/gi, '\n')
      .replace(/<[^>]*>/g, ''),
  );
  return text
    .replace(/\(?Feed generated with FetchRSS\)?|Generated by RSS\.app/gi, '')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const httpsUrl = (u: unknown) => {
  if (typeof u !== 'string') return null;
  const s = decode(u.trim());
  return /^https:\/\/[^\s"'<>]+$/i.test(s) ? s : null;
};
const firstImg = (html: string) => httpsUrl(/<img[^>]+src=["']([^"']+)["']/i.exec(html)?.[1]);
const isoDate = (d: unknown) => {
  const t = typeof d === 'string' ? Date.parse(d) : NaN;
  return Number.isFinite(t) ? new Date(t).toISOString() : null;
};

/** The text, unless it only repeats the start of the title (rss.app titles are the text, cut short). */
function bestText(title: string, body: string) {
  const t = title.replace(/\s*(\.\.\.|…)$/, '').trim();
  if (!body) return t;
  if (!t || body.replace(/\s+/g, ' ').startsWith(t.replace(/\s+/g, ' '))) return body;
  return body.length >= t.length ? body : t;
}

function parseJsonFeed(json: unknown): FacebookPost[] {
  const items = (json as { items?: unknown })?.items;
  if (!Array.isArray(items)) return [];
  return items.flatMap((raw): FacebookPost[] => {
    const it = raw as Record<string, unknown>;
    const url = httpsUrl(it.url) ?? httpsUrl(it.external_url);
    if (!url) return [];
    const html = typeof it.content_html === 'string' ? it.content_html : '';
    const body = typeof it.content_text === 'string' && it.content_text.trim() ? plainText(it.content_text) : plainText(html);
    const attach = Array.isArray(it.attachments) ? (it.attachments as Record<string, unknown>[]).find((a) => String(a?.mime_type ?? '').startsWith('image/')) : undefined;
    const image = httpsUrl(it.image) ?? httpsUrl(attach?.url) ?? firstImg(html);
    const text = bestText(plainText(String(it.title ?? '')), body);
    if (!text && !image) return [];
    return [{ id: String(it.id ?? url), url, text, image, postedAt: isoDate(it.date_published ?? it.date_modified) }];
  });
}

const tag = (xml: string, name: string) => new RegExp(`<${name}(?:\\s[^>]*)?>([\\s\\S]*?)</${name}>`, 'i').exec(xml)?.[1] ?? '';
const attr = (xml: string, name: string, at: string) => new RegExp(`<${name}\\s[^>]*${at}=["']([^"']+)["']`, 'i').exec(xml)?.[1];

function parseRss(xml: string): FacebookPost[] {
  const items = xml.match(/<item[\s>][\s\S]*?<\/item>/gi) ?? [];
  return items.flatMap((it): FacebookPost[] => {
    const url = httpsUrl(plainText(tag(it, 'link'))) ?? httpsUrl(plainText(tag(it, 'guid')));
    if (!url) return [];
    const html = tag(it, 'content:encoded') || tag(it, 'description');
    const rawHtml = html.replace(/<!\[CDATA\[|\]\]>/g, '');
    const htmlDecoded = rawHtml.includes('&lt;') ? decode(rawHtml) : rawHtml;
    const enclosure = /type=["']image\//i.test(it) ? attr(it, 'enclosure', 'url') : undefined;
    const image = httpsUrl(attr(it, 'media:content', 'url')) ?? httpsUrl(attr(it, 'media:thumbnail', 'url')) ?? httpsUrl(enclosure) ?? firstImg(htmlDecoded);
    const text = bestText(plainText(tag(it, 'title')), plainText(htmlDecoded));
    if (!text && !image) return [];
    return [{ id: plainText(tag(it, 'guid')) || url, url, text, image, postedAt: isoDate(plainText(tag(it, 'pubDate'))) }];
  });
}

/** Posts from an rss.app feed, JSON or RSS, newest first. */
export function parseFacebookFeed(body: string): FacebookPost[] {
  const trimmed = body.trimStart();
  let posts: FacebookPost[];
  if (trimmed.startsWith('{')) {
    try {
      posts = parseJsonFeed(JSON.parse(trimmed));
    } catch {
      posts = [];
    }
  } else posts = parseRss(trimmed);
  const seen = new Set<string>();
  return posts
    .filter((p) => (seen.has(p.url) ? false : (seen.add(p.url), true)))
    .sort((a, b) => (b.postedAt ? Date.parse(b.postedAt) : 0) - (a.postedAt ? Date.parse(a.postedAt) : 0))
    .slice(0, KEEP);
}
