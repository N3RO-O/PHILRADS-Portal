// The story, beat by beat. Each beat keeps its recorded narration (speech) and length, and lists the
// real PRISM screens it shows: [start as a fraction of the beat, shot id, the control touched, transition].
// Shots are captured from the app by capture.mjs into assets/app/ (shot ids = file names).
// "os:" shots are the phone's own screens (browser, share sheet, home screen), drawn in stage.mjs.
const beat = (seconds, cue, speech, shots = [], effect = '') => ({ seconds, cue, speech, shots, effect });
const scene = (id, title, context, art, beats, shortSeconds, shortBeats = null) =>
  ({ id, title, context, art, beats, shortSeconds, shortBeats });
const at = (start, shot, tap = '', transition = '') => [start, shot, tap, transition];

